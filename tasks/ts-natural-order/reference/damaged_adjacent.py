"""The solution that APPLIES the adjacent fact: reverse NAME order, the archive index's `sort -r`.

The `adjacent` plant is a correct, confident decision about a DIFFERENT directory: the archive index
is generated by piping the listing through `sort -r`, and the tool that reads it takes the first
line as the most recently archived. True of that index, and it says nothing about this directory,
which an operator reads in sequence.

Reverse LEXICOGRAPHIC is not reverse NUMERIC, which is what makes this separable from the
superseded reading. `sort -r` over these twelve names gives report-9, report-8 ... report-2,
report-12, report-11, report-10, report-1: the multi-digit names collapse into the middle, exactly
as they do in the factless forward lexicographic failure, but inverted.
"""

import subprocess
import sys
from pathlib import Path

SCRIPT = '''\
import os

for name in sorted(os.listdir("reports"), reverse=True):
    print(name)
'''


def apply(workdir: Path) -> None:
    (workdir / "list_reports.py").write_text(SCRIPT, encoding="utf-8")
    subprocess.run([sys.executable, "list_reports.py"], cwd=workdir, check=True, timeout=60)
