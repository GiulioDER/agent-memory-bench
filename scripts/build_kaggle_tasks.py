"""Generate the two Kaggle Benchmarks task files for the memory-discipline benchmark.

Each file is self-contained, because a Kaggle task runs as a notebook with no access to this
repository: it carries `kaggle_memory/scoring.py` verbatim and its half of `items.json`. The
benchmark on Kaggle groups the two tasks, so its average is the headline discipline score.

    python scripts/build_kaggle_tasks.py          # write kaggle_memory/tasks/*.py
    python scripts/build_kaggle_tasks.py --check  # exit 1 if the committed files are stale
"""

import hashlib
import json
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
PACKAGE = REPO / "kaggle_memory"
OUT = PACKAGE / "tasks"

FAMILIES = {
    "trust": ("TRUST_CONDITIONS", "Apply the memory where it answers the task: present, superseded."),
    "restraint": ("RESTRAINT_CONDITIONS",
                  "Ask where memory does not answer the task: absent, adjacent, contradictory."),
}

TEMPLATE = '''# %%
# Memory discipline benchmark, {family} half. {blurb}
#
# GENERATED by scripts/build_kaggle_tasks.py in github.com/GiulioDER/agent-memory-bench.
# Do not edit by hand. items.json sha256: {items_sha}  scoring.py sha256: {scoring_sha}
#
# Each item puts the model in a coding task with a set of memory search results, and asks it to
# end with `VALUE: <value>` or `ASK: <question>`. Only the memory differs between the items of a
# scenario. The score is the unweighted mean of per-condition accuracy.
import json

import kaggle_benchmarks as kbench
import pandas as pd

# %%
# ---- kaggle_memory/scoring.py, verbatim ----
{scoring}
# ---- end of kaggle_memory/scoring.py ----

# %%
ITEMS = json.loads(r\'\'\'{items_json}\'\'\')
BY_ID = {{item["item_id"]: item for item in ITEMS}}
MAX_ERRORED_SHARE = 0.05


@kbench.task(name="memory-discipline-{family}-item", store_task=False)
def answer_item(llm, item_id: str) -> dict:
    item = BY_ID[item_id]
    reply = llm.prompt(item["prompt"])
    return classify(item, reply)


@kbench.task(name="memory-discipline-{family}")
def memory_discipline_{family}(llm) -> float:
    frame = pd.DataFrame({{"item_id": [item["item_id"] for item in ITEMS]}})
    with kbench.client.enable_cache():
        runs = answer_item.evaluate(
            llm=[llm],
            evaluation_data=frame,
            n_jobs=4,
            on_failure="continue",
            max_attempts=3,
            retry_delay=15,
        )
    results = [run.result for run in runs.completed_runs.runs]
    errored = len(ITEMS) - len(results)
    table = condition_accuracy(results)
    score = family_score(results, {conditions})
    print("MEMORY_DISCIPLINE_SUMMARY " + json.dumps({{
        "family": "{family}",
        "items": len(ITEMS),
        "completed": len(results),
        "errored": errored,
        "by_condition": {{c: {{"correct": hit, "n": n}} for c, (hit, n) in table.items()}},
        "score": score,
    }}))
    print("MEMORY_DISCIPLINE_ITEMS " + json.dumps(results))
    kbench.assertions.assert_true(
        errored <= MAX_ERRORED_SHARE * len(ITEMS),
        expectation="at most 5% of items may error; a run above that is incomplete",
    )
    return score


memory_discipline_{family}.run(kbench.llm)
'''


def _sha(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def render() -> dict[str, str]:
    scoring = (PACKAGE / "scoring.py").read_text(encoding="utf-8")
    items_bytes = (PACKAGE / "items.json").read_bytes()
    items = json.loads(items_bytes)
    files = {}
    for family, (conditions, blurb) in FAMILIES.items():
        half = [item for item in items if item["family"] == family]
        items_json = json.dumps(half, indent=1, ensure_ascii=False)
        if "'''" in items_json or items_json.endswith("\\"):
            raise SystemExit("items cannot be embedded in a raw triple-quoted string")
        files[f"memory_discipline_{family}.py"] = TEMPLATE.format(
            family=family,
            blurb=blurb,
            items_sha=_sha(items_bytes),
            scoring_sha=_sha(scoring.encode("utf-8")),
            scoring=scoring.rstrip("\n"),
            items_json=items_json,
            conditions=conditions,
        )
    return files


def main(argv: list[str]) -> int:
    files = render()
    if "--check" in argv:
        stale = [name for name, text in files.items()
                 if not (OUT / name).exists()
                 or (OUT / name).read_text(encoding="utf-8") != text]
        for name in stale:
            print(f"stale: kaggle_memory/tasks/{name}; run scripts/build_kaggle_tasks.py")
        return 1 if stale else 0
    OUT.mkdir(exist_ok=True)
    for name, text in files.items():
        (OUT / name).write_text(text, encoding="utf-8", newline="\n")
        print(f"wrote kaggle_memory/tasks/{name}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
